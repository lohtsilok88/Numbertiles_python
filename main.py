"""Number Tiles puzzle (3x3, 4x4, or 5x5).

Each move subtracts one (modulo max_value + 1) from every tile in the
selected row and column. Levels are generated by applying exactly `size`
random moves to the solved board, so every generated level is solvable.
"""

import random
import sys

import pygame


# Colors
BG = (15, 23, 42)
PANEL = (30, 41, 59)
BORDER = (71, 85, 105)
TILE = (30, 41, 59)
ZERO = (15, 23, 42)
TEXT = (248, 250, 252)
MUTED = (148, 163, 184)
BLUE = (59, 130, 246)
AMBER = (245, 158, 11)
RED = (239, 68, 68)
GREEN = (16, 185, 129)

MIN_SIZE, MAX_SIZE = 3, 5
TILE_GAP = 7
BOARD_PAD = 12
MARGIN = 24
CONTROL_GAP = 18
BUTTON_H = 42


class NumberTiles:
    def __init__(self):
        pygame.init()
        pygame.display.set_caption("Number Tiles")
        self.font = pygame.font.SysFont(None, 28)
        self.small_font = pygame.font.SysFont(None, 22)
        self.title_font = pygame.font.SysFont(None, 34, bold=True)
        self.size = 3
        self.max_value = 4
        self.history = []
        self.status = ""
        self.build_level()
        self.resize_window()
        self.clock = pygame.time.Clock()

    def allowed_max(self, size):
        return {3: (3, 4), 4: (3, 5), 5: (4, 6)}[size]

    def tile_size(self):
        # Keep the complete 5x5 board comfortably within typical laptop widths.
        return 66

    def board_rect(self):
        tile = self.tile_size()
        side = self.size * tile + (self.size - 1) * TILE_GAP + BOARD_PAD * 2
        return pygame.Rect((self.width - side) // 2, self.board_top, side, side)

    def layout(self):
        self.width = 520
        self.board_top = 104
        self.board = self.board_rect()
        # Controls begin strictly below the board's actual bottom edge.
        self.controls_top = self.board.bottom + CONTROL_GAP
        self.height = self.controls_top + 2 * BUTTON_H + 48 + MARGIN
        self.size_button = pygame.Rect(MARGIN, 30, 120, 42)
        self.value_button = pygame.Rect(156, 30, 150, 42)
        self.undo_button = pygame.Rect(MARGIN, self.controls_top, 224, BUTTON_H)
        self.reset_button = pygame.Rect(self.width - MARGIN - 224, self.controls_top, 224, BUTTON_H)
        self.status_y = self.controls_top + BUTTON_H + 16

    def resize_window(self):
        self.layout()
        self.screen = pygame.display.set_mode((self.width, self.height), pygame.RESIZABLE)
        # Set the intended initial size even if the user later resizes the window.
        pygame.display.set_mode((self.width, self.height), pygame.RESIZABLE)

    def sync_max_value(self):
        low, high = self.allowed_max(self.size)
        self.max_value = max(low, min(high, self.max_value))

    def change_size(self, delta):
        self.size = max(MIN_SIZE, min(MAX_SIZE, self.size + delta))
        self.sync_max_value()
        self.build_level()
        self.resize_window()

    def change_max(self, delta):
        low, high = self.allowed_max(self.size)
        self.max_value = max(low, min(high, self.max_value + delta))
        self.build_level()

    def apply_move(self, board, row, col, solving):
        modulus = self.max_value + 1
        step = -1 if solving else 1
        for c in range(self.size):
            board[row][c] = (board[row][c] + step) % modulus
        for r in range(self.size):
            if r != row:
                board[r][col] = (board[r][col] + step) % modulus

    def build_level(self):
        self.sync_max_value()
        # A scramble is the result of legal moves from the solved board, so
        # reversing those moves always solves it. Reject boards with zeros,
        # matching the source game's starting-board rule.
        while True:
            board = [[0] * self.size for _ in range(self.size)]
            for _ in range(self.size):
                self.apply_move(board, random.randrange(self.size), random.randrange(self.size), False)
            if all(value != 0 for row in board for value in row):
                break
        self.board_state = board
        self.initial_board = [row[:] for row in board]
        self.history = []
        self.status = ""
        self.layout()
        if hasattr(self, "screen"):
            self.screen = pygame.display.set_mode((self.width, self.height), pygame.RESIZABLE)

    def undo(self):
        if self.history:
            self.board_state = self.history.pop()
            self.status = ""

    def reset(self):
        if self.history:
            self.board_state = [row[:] for row in self.initial_board]
            self.history.clear()
            self.status = ""

    def draw_button(self, rect, label, color, enabled=True):
        fill = color if enabled else (75, 85, 99)
        pygame.draw.rect(self.screen, fill, rect, border_radius=8)
        pygame.draw.rect(self.screen, BORDER, rect, width=1, border_radius=8)
        image = self.font.render(label, True, BG if color == AMBER and enabled else TEXT)
        self.screen.blit(image, image.get_rect(center=rect.center))

    def draw(self):
        self.screen.fill(BG)
        self.draw_button(self.size_button, f"Grid: {self.size}  -/+", PANEL)
        self.draw_button(self.value_button, f"Max: {self.max_value}  -/+", PANEL)

        board_rect = self.board_rect()
        pygame.draw.rect(self.screen, BORDER, board_rect, border_radius=12)
        tile = self.tile_size()
        for row in range(self.size):
            for col in range(self.size):
                x = board_rect.x + BOARD_PAD + col * (tile + TILE_GAP)
                y = board_rect.y + BOARD_PAD + row * (tile + TILE_GAP)
                rect = pygame.Rect(x, y, tile, tile)
                value = self.board_state[row][col]
                pygame.draw.rect(self.screen, ZERO if value == 0 else TILE, rect, border_radius=8)
                pygame.draw.rect(self.screen, (30, 41, 59) if value == 0 else BORDER,
                                 rect, width=2, border_radius=8)
                image = self.title_font.render(str(value), True, MUTED if value == 0 else TEXT)
                self.screen.blit(image, image.get_rect(center=rect.center))

        self.draw_button(self.undo_button, "Undo", AMBER, bool(self.history))
        self.draw_button(self.reset_button, "Reset", RED, bool(self.history))
        status = self.status or f"Goal: solve in exactly {self.size} moves"
        color = GREEN if self.status else MUTED
        image = self.small_font.render(status, True, color)
        self.screen.blit(image, image.get_rect(center=(self.width // 2, self.status_y)))
        pygame.display.flip()

    def board_cell_at(self, pos):
        rect = self.board_rect()
        inner_x = pos[0] - rect.x - BOARD_PAD
        inner_y = pos[1] - rect.y - BOARD_PAD
        stride = self.tile_size() + TILE_GAP
        col, row = inner_x // stride, inner_y // stride
        if not (0 <= row < self.size and 0 <= col < self.size):
            return None
        if inner_x % stride >= self.tile_size() or inner_y % stride >= self.tile_size():
            return None
        return int(row), int(col)

    def handle_click(self, pos):
        if self.size_button.collidepoint(pos):
            # The button cycles through supported board sizes.
            self.change_size(1 if self.size < MAX_SIZE else MIN_SIZE - MAX_SIZE)
            return
        if self.value_button.collidepoint(pos):
            low, high = self.allowed_max(self.size)
            self.change_max(1 if self.max_value < high else low - high)
            return
        if self.undo_button.collidepoint(pos):
            self.undo()
            return
        if self.reset_button.collidepoint(pos):
            self.reset()
            return
        cell = self.board_cell_at(pos)
        if cell is None or all(v == 0 for row in self.board_state for v in row):
            return
        self.history.append([row[:] for row in self.board_state])
        self.apply_move(self.board_state, *cell, solving=True)
        if all(v == 0 for row in self.board_state for v in row):
            self.status = "SOLVED!"

    def run(self):
        running = True
        while running:
            for event in pygame.event.get():
                if event.type == pygame.QUIT:
                    running = False
                elif event.type == pygame.VIDEORESIZE:
                    # Keep a minimum width sufficient for the buttons; compute
                    # height from the board so the footer never covers it.
                    self.width = max(500, event.w)
                    self.layout()
                    self.height = max(event.h, self.controls_top + 2 * BUTTON_H + 48 + MARGIN)
                    self.screen = pygame.display.set_mode((self.width, self.height), pygame.RESIZABLE)
                elif event.type == pygame.MOUSEBUTTONDOWN and event.button == 1:
                    self.handle_click(event.pos)
            self.draw()
            self.clock.tick(60)
        pygame.quit()
        sys.exit()


if __name__ == "__main__":
    NumberTiles().run()
